'use strict';
const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('amethyst', {
  desktop: true,
  setGround: (color) => ipcRenderer.send('ground', String(color)),
  hitchLog: (lines) => ipcRenderer.send('hitch-log', lines),
  hitchMetrics: (why) => ipcRenderer.send('hitch-metrics', String(why)),
  hitchWindow: (on) => ipcRenderer.invoke('hitch-window', on === true || on === null ? on : 'ask'),
  onHitchPop: (fn) => void ipcRenderer.on('hitch-pop', (e, on) => fn(!!on)),
  hitchTail: () => ipcRenderer.invoke('hitch-tail'),
  onHitch: (fn) => void ipcRenderer.on('hitch-lines', (e, text) => fn(String(text))),
  hitchFolder: () => ipcRenderer.invoke('hitch-folder'),
  hitchSnapshot: () => ipcRenderer.invoke('hitch-snapshot'),
  hitchRecord: () => ipcRenderer.invoke('hitch-record'),
  onHitchDump: (fn) => void ipcRenderer.on('hitch-dump', (e, id) => ipcRenderer.send('hitch-dump', { id, ...fn() })),
  webview: true,
  onBrowserOpen: (fn) => void ipcRenderer.on('browser-open', (e, d) => fn(d)),
  onBrowserZoom: (fn) => void ipcRenderer.on('browser-zoom', (e, d) => fn(d)),
  capturePage: (id) => ipcRenderer.invoke('capture-page', +id),
  pickFolder: (opts = {}) => ipcRenderer.invoke('pick-folder', { title: String(opts.title || ''), defaultPath: String(opts.defaultPath || '') }),
  pickFiles: () => ipcRenderer.invoke('pick-files'),
  clipboardFiles: () => ipcRenderer.invoke('clipboard-files'),
  edit: (what) => ipcRenderer.send('edit', String(what)),
  pathOf: (file) => webUtils.getPathForFile(file),
  onFiles: (fn) => void ipcRenderer.on('files', () => fn()),
  takeFiles: () => ipcRenderer.invoke('take-files'),
  defaultApps: () => ipcRenderer.invoke('default-apps'),
  newAmethyst: () => ipcRenderer.invoke('new-amethyst'),
  amethysts: () => ipcRenderer.invoke('amethysts'),
  openAmethyst: (n) => ipcRenderer.invoke('open-amethyst', Number(n)),
  forgetAmethyst: (n) => ipcRenderer.invoke('forget-amethyst', Number(n)),
  trayState: () => ipcRenderer.invoke('tray-state'),
  traySet: (c) => ipcRenderer.invoke('tray-set', { ...('on' in c ? { on: !!c.on } : {}), ...('login' in c ? { login: !!c.login } : {}) }),
  forgetWindow: (at) => ipcRenderer.invoke('forget-window', at === undefined ? 'ask' : at && { x: +at.x, y: +at.y, width: +at.width, height: +at.height, near: !!at.near }),
  onForgetPop: (fn) => void ipcRenderer.on('forget-pop', (e, on) => fn(!!on)),
  forgetGuide: (on) => ipcRenderer.invoke('forget-guide', on === null ? null : true),
  forgetToast: (o) => ipcRenderer.invoke('forget-toast', { text: String(o?.text ?? ''), level: Number(o?.level) || 1, id: String(o?.id ?? ''), again: String(o?.again ?? ''), from: String(o?.from ?? '') }),
  forgetList: (list) => ipcRenderer.invoke('forget-list', list),
  toastAct: (what) => ipcRenderer.send('forget-toast-act', String(what)),
  onForgetAct: (fn) => void ipcRenderer.on('forget-act', (e, what) => fn(String(what))),
  quickWindow: (kind, at) => ipcRenderer.invoke('quick-window', String(kind), at === undefined ? 'ask' : at === 'show' || at === null ? at : { x: +at.x, y: +at.y, width: +at.width, height: +at.height }),
  onQuickPop: (fn) => void ipcRenderer.on('quick-pop', (e, kinds) => fn([...kinds])),
  onQtermClaim: (fn) => void ipcRenderer.on('qterm-claim', (e, d) => fn({ kind: String(d?.kind || ''), wid: String(d?.wid || ''), pid: String(d?.pid || ''), am: Number(d?.am) || 1 })),
  minimizeWindow: () => ipcRenderer.invoke('window-away'),
  claimSpare: (of, opts) => ipcRenderer.invoke('claim-spare', String(of), opts && typeof opts === 'object' ? { pop: opts.pop !== false, kind: String(opts.kind || ''), addr: opts.addr ? String(opts.addr) : '', bounds: opts.bounds && typeof opts.bounds === 'object' ? { x: +opts.bounds.x, y: +opts.bounds.y, width: +opts.bounds.width, height: +opts.bounds.height } : null } : undefined),
  atProject: (wid, pid) => ipcRenderer.invoke('at-project', String(wid ?? ''), String(pid ?? '')),
  windowAlive: (of, n) => ipcRenderer.invoke('window-alive', String(of), Number(n)),
  quickOf: () => ipcRenderer.invoke('quick-of'),
  soloFront: (kind) => ipcRenderer.invoke('solo-front', String(kind)),
  focusPid: (pid) => ipcRenderer.invoke('focus-pid', Number(pid)),
  flash: () => ipcRenderer.invoke('flash-frame'),
  showWindow: (kind, focus) => ipcRenderer.invoke('window-back', kind === undefined ? '' : String(kind), !!focus),
  onAway: (fn) => {
    ipcRenderer.on('away', (e, kinds) => fn([...kinds]));
    ipcRenderer.invoke('away-list').then((kinds) => fn([...kinds]));
  },
  sizeWindow: (k) => ipcRenderer.invoke('window-size', +k),
  zoomWindow: () => ipcRenderer.invoke('window-zoom'),
  osWindow: (what) => ipcRenderer.invoke('window-os', ['max', 'ask'].includes(what) ? what : 'min'),
  onSize: (fn) => {
    ipcRenderer.on('size', (e, k) => fn(k));
    ipcRenderer.invoke('size-now').then(fn);
  },
  dragWindow: (phase, color) => ipcRenderer.send('window-drag', String(phase), String(color || '')),
  onAskClose: (fn) => void ipcRenderer.on('ask-close', () => fn()),
  closeWindow: (answer) => ipcRenderer.send('close-window', answer === 'asking' ? 'asking' : answer === true),
  holdClose: () => ipcRenderer.sendSync('hold-close') === true,
  closeHeld: () => ipcRenderer.invoke('close-held'),
  update: {
    state: () => ipcRenderer.invoke('update-state'),
    onState: (fn) => void ipcRenderer.on('update', (e, s) => fn(s)),
    seen: () => ipcRenderer.invoke('update-seen'),
    check: () => ipcRenderer.invoke('update-check'),
    download: () => ipcRenderer.invoke('update-download'),
    cancel: () => ipcRenderer.invoke('update-cancel'),
    install: () => ipcRenderer.invoke('update-install'),
    set: ({ look, auto }) => ipcRenderer.invoke('update-set', { look: !!look, auto: !!auto }),
  },
  report: {
    onRing: (fn) => void ipcRenderer.on('report-ring', (e, r) => fn(r)),
    onGo: (fn) => void ipcRenderer.on('report-go', (e, id) => fn(String(id))),
    open: (id, am) => ipcRenderer.send('report-open', String(id), Number(am) || 1),
    act: (what, n) => ipcRenderer.send('ring-act', String(what), Number(n) || 0),
    seen: (id) => ipcRenderer.send('report-seen', String(id)),
    onUnring: (fn) => void ipcRenderer.on('report-unring', (e, id) => fn(String(id))),
    noticeScreen: (v) => ipcRenderer.send('notice-screen', v === 'main' ? 'main' : 'own'),
    cacheNotice: (on) => ipcRenderer.send('cache-notice', on !== false),
  },
  usage: {
    state: () => ipcRenderer.invoke('usage-state'),
    onState: (fn) => void ipcRenderer.on('usage', (e, s) => fn(s)),
    set: ({ on, asked }) => ipcRenderer.invoke('usage-set', { on: on === true || on === false ? on : null, asked: !!asked }),
  },
  license: {
    state: () => ipcRenderer.invoke('license-state'),
    onState: (fn) => void ipcRenderer.on('license', (e, s) => fn(s)),
    accept: (version) => ipcRenderer.invoke('license-accept', { version: String(version || '') }),
  },
});
